export function formatPrice(priceEur: number, currency: CurrencyConfig): string {
  const converted = Math.round(priceEur * currency.rateToEur);
  if (currency.code === 'EGP') {
    return `${converted.toLocaleString()} E£`;
  }
  return `${currency.symbol}${converted.toLocaleString()}`;
}
